test('backup preflight reports overwrites, restore remaps identities and is repeatable; old backups keep prompts',async()=>{
 const first=await create();await call(detail.onRequestPatch,ctx({is_favorite:true},'PATCH',String(first.id)))
 const backup=await exportBackup(store.db)
 assert.equal(backup.prompts.length,1);assert.equal(backup.prompt_categories.length,1)
 backup.prompts[0].content='restored\\\n';backup.prompts[0].id=99;backup.prompt_categories[0].id=88;backup.prompts[0].category_id=88
 const preview=await restoreBackup(store.db,backup,{dryRun:true})
 assert.equal(preview.status,200);assert.equal(preview.data.prompts_overwritten,1)
 assert.notEqual(store.sql('SELECT content FROM prompts')[0].content,'restored\\\n')
 for(let n=0;n<2;n++)assert.equal((await restoreBackup(store.db,backup)).status,200)
 assert.deepEqual(store.sql('SELECT content,is_favorite FROM prompts'),[{content:'restored\\\n',is_favorite:1}])
 assert.equal((await restoreBackup(store.db,{format_version:1,websites:[],domains:[]})).status,200)
 assert.equal(store.sql('SELECT COUNT(*) n FROM prompts')[0].n,1)
 store.init();assert.equal((await restoreBackup(store.db,backup)).status,200)
 assert.equal(store.sql('SELECT name FROM prompt_categories')[0].name,'运营')
 assert.equal(store.sql('SELECT content FROM prompts')[0].content,'restored\\\n')
})
